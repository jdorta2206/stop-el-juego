let cachedAudio: HTMLAudioElement | null = null;

function getAudio(): HTMLAudioElement | null {
  if (typeof window === "undefined") return null;
  if (!cachedAudio) {
    const audio = new Audio(HALLOWEEN_SCARE_AUDIO);
    audio.preload = "auto";
    audio.volume = 0.95;
    cachedAudio = audio;
  }
  return cachedAudio;
}

export function preloadHalloweenScareAudio(): void {
  const audio = getAudio();
  try { audio?.load(); } catch {}
}

export async function playHalloweenScareAudio(): Promise<void> {
  const audio = getAudio();
  if (!audio) return;
  try {
    audio.currentTime = 0;
    await audio.play();
  } catch {}
}
